#define NINODES 200

// Disk layout:
// [ boot block | sb block | log | inode blocks | free bit map | data blocks ]

ціле nbitmap = FSSIZE / BPB + 1;
ціле ninodeblocks = NINODES / IPB + 1;
ціле nlog = LOGBLOCKS + 1; // Header followed by LOGBLOCKS data blocks.
ціле nmeta;   // Number of meta blocks (boot, sb, nlog, inode, bitmap)
ціле nblocks; // Number of data blocks

ціле fsfd;
struct superblock sb;
char zeroes[BSIZE];
uint freeinode = 1;
uint freeblock;

